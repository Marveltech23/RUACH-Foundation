-- 1. GALLERY TABLE
create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'events',
  image_url text not null,
  created_at timestamptz not null default now()
);

-- 2. BLOGS TABLE
create table if not exists public.blogs (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  category text not null default 'Leadership',
  author text not null default 'RUACH Editorial',
  excerpt text,
  content text not null,
  featured_image_url text,
  published boolean not null default false,
  published_at timestamptz default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 3. EVENTS TABLE
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  event_date date not null,
  start_time text,
  end_time text,
  venue text,
  banner_url text,
  registration_open boolean not null default true,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

-- 4. EVENT REGISTRATIONS TABLE
create table if not exists public.event_registrations (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  event_title text,
  full_name text not null,
  email text not null,
  phone text,
  organization text,
  created_at timestamptz not null default now()
);

-- 5. DONATIONS TABLE
create table if not exists public.donations (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  donation_type text not null default 'One-Time Gift',
  amount numeric(12, 2) not null,
  currency text not null default 'NGN',
  payment_method text not null default 'paystack',
  payment_reference text,
  status text not null default 'completed',
  created_at timestamptz not null default now()
);

-- 6. CONTACT & PARTNERSHIP INQUIRIES TABLE
create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  type text not null default 'contact', -- 'contact' or 'partnership'
  full_name text not null,
  email text not null,
  organization text,
  subject text,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

-- ── INDEXES ───────────────────────────────────────────────────────────────────
create index if not exists idx_blogs_slug on public.blogs (slug);
create index if not exists idx_blogs_published on public.blogs (published, published_at desc);
create index if not exists idx_events_published on public.events (published, event_date asc);
create index if not exists idx_event_regs_event on public.event_registrations (event_id, created_at desc);
create index if not exists idx_donations_created on public.donations (created_at desc);
create index if not exists idx_inquiries_created on public.inquiries (created_at desc);

-- ── ROW LEVEL SECURITY (RLS) ──────────────────────────────────────────────────
alter table public.gallery enable row level security;
alter table public.blogs enable row level security;
alter table public.events enable row level security;
alter table public.event_registrations enable row level security;
alter table public.donations enable row level security;
alter table public.inquiries enable row level security;

-- Public (anon) read access for public content
drop policy if exists "Public can view gallery" on public.gallery;
create policy "Public can view gallery" on public.gallery
  for select using (true);

drop policy if exists "Public can view published blogs" on public.blogs;
create policy "Public can view published blogs" on public.blogs
  for select using (published = true);

drop policy if exists "Public can view published events" on public.events;
create policy "Public can view published events" on public.events
  for select using (published = true);

-- Public (anon) insert access for registrations, donations & inquiries
drop policy if exists "Public can register for events" on public.event_registrations;
create policy "Public can register for events" on public.event_registrations
  for insert with check (true);

drop policy if exists "Public can record donations" on public.donations;
create policy "Public can record donations" on public.donations
  for insert with check (true);

drop policy if exists "Public can submit inquiries" on public.inquiries;
create policy "Public can submit inquiries" on public.inquiries
  for insert with check (true);

-- Authenticated Admin full access on all tables
drop policy if exists "Admins manage gallery" on public.gallery;
create policy "Admins manage gallery" on public.gallery
  for all to authenticated using (true) with check (true);

drop policy if exists "Admins manage blogs" on public.blogs;
create policy "Admins manage blogs" on public.blogs
  for all to authenticated using (true) with check (true);

drop policy if exists "Admins manage events" on public.events;
create policy "Admins manage events" on public.events
  for all to authenticated using (true) with check (true);

drop policy if exists "Admins manage registrations" on public.event_registrations;
create policy "Admins manage registrations" on public.event_registrations
  for all to authenticated using (true) with check (true);

drop policy if exists "Admins manage donations" on public.donations;
create policy "Admins manage donations" on public.donations
  for all to authenticated using (true) with check (true);

drop policy if exists "Admins manage inquiries" on public.inquiries;
create policy "Admins manage inquiries" on public.inquiries
  for all to authenticated using (true) with check (true);

-- ── STORAGE BUCKET FOR IMAGES (gallery, blog covers, event banners) ──────────
insert into storage.buckets (id, name, public)
values ('ruach-media', 'ruach-media', true)
on conflict (id) do nothing;

drop policy if exists "Public can view ruach-media" on storage.objects;
create policy "Public can view ruach-media" on storage.objects
  for select using (bucket_id = 'ruach-media');

drop policy if exists "Admins can upload to ruach-media" on storage.objects;
create policy "Admins can upload to ruach-media" on storage.objects
  for insert to authenticated with check (bucket_id = 'ruach-media');

drop policy if exists "Admins can update ruach-media" on storage.objects;
create policy "Admins can update ruach-media" on storage.objects
  for update to authenticated using (bucket_id = 'ruach-media');

drop policy if exists "Admins can delete from ruach-media" on storage.objects;
create policy "Admins can delete from ruach-media" on storage.objects
  for delete to authenticated using (bucket_id = 'ruach-media');
